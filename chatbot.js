// تابع جستجو در سوالات
function getAnswer(question) {
    const normalizedQuestion = question.trim().toLowerCase();
    
    // جستجو بر اساس کلمات کلیدی
    for (let i = 0; i < FAQ.length; i++) {
        const q = FAQ[i].question.toLowerCase();
        if (q.includes(normalizedQuestion) || normalizedQuestion.includes(q)) {
            return FAQ[i].answer;
        }
    }
    
    // جستجو بر اساس کلمه
    for (let i = 0; i < FAQ.length; i++) {
        const q = FAQ[i].question.toLowerCase();
        const words = normalizedQuestion.split(" ");
        for (let word of words) {
            if (word.length > 2 && q.includes(word)) {
                return FAQ[i].answer;
            }
        }
    }
    
    // اگر جوابی پیدا نشد
    return "سوال شما را متوجه نشدم. لطفاً یکی از این موضوعات را بپرسید:\n• ساخت کلاس\n• اضافه کردن دانش‌آموز\n• ثبت نمره\n• حضور غیاب\n• گزارش ماهانه\n• پشتیبان‌گیری";
}